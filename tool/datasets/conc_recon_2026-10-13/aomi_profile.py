import sys, re
import pandas as pd
df = pd.read_csv(sys.argv[1], low_memory=False)
ncei = pd.read_csv(sys.argv[2], low_memory=False, encoding='utf-8-sig')
norm = lambda s: re.sub(r'^https?://(dx\.)?doi\.org/', '', str(s).strip().lower())
ncei_dois = set(norm(x) for x in ncei['DOI'].dropna())
print('NCEI distinct DOIs', len(ncei_dois))
print(df['0022:Processing level'].value_counts(dropna=False))
print(df['0021:QC Data grade'].value_counts(dropna=False).head())
print(df['0018:Creative commons license'].value_counts(dropna=False).head(10))
print('dates', df['0033:Sampling start Date'].min(), df['0033:Sampling start Date'].max())
print('lat nonnull', df['0045:GPS_Lat Int'].notna().sum())
for c in ['0192:Particle density_m3 (d<5mm)','0194:Particle density_km2 (d<5mm)','0204:Particle density_m3 (1-d<5mm)','0206:Particle density_km2 (1-d<5mm)','0216:Particle density_m3 (d<1mm)','0218:Particle density_km2 (d<1mm)','0228:Particle density_m3 (5mm-d)','0070:Mesh openings (mm)']:
    print(c, df[c].notna().sum())
print(df['0070:Mesh openings (mm)'].value_counts().head(8))
print(df['0056:Equipment Type'].value_counts().head(8))
print(df['0006:Location'].value_counts().head(12))
dois = df['0016:DOI'].dropna().map(norm)
u = sorted(set(dois)); print('AOMI distinct DOIs', len(u), 'rows with DOI', len(dois))
inn = [d for d in u if d in ncei_dois]; print('AOMI DOIs also in NCEI:', len(inn))
rows_in = dois.isin(ncei_dois).sum(); print('AOMI rows whose DOI is in NCEI:', rows_in)
import random; random.seed(1)
for d in random.sample(u, min(8, len(u))): print(' sample', d, d in ncei_dois)
print('top DOIs'); print(dois.value_counts().head(15))
print(df['0009:Organization'].value_counts().head(12))
print(df['0023:Processing methods'].value_counts().head(6))
